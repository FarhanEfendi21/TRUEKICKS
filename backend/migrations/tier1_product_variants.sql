ALTER TABLE product_variants DISABLE ROW LEVEL SECURITY;

GRANT EXECUTE ON FUNCTION deduct_variant_stocks(JSONB) TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION restore_variant_stocks(JSONB) TO anon, authenticated, service_role;

DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE product_variants;
EXCEPTION
  WHEN duplicate_object THEN NULL;
  WHEN undefined_object THEN NULL;
END $$;
