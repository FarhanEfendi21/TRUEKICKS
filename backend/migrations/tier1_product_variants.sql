-- ============================================================
-- TrueKicks Tier 1 Migration:
-- Real-Time Inventory per Size (product_variants) + Atomic Stock RPCs
-- 1. product_variants table with canonical (product_type, product_id, size)
-- 2. Idempotent seed for existing sneakers, apparel, and orphan catalog rows
-- 3. Atomic row-locking RPC deduct_variant_stocks(JSONB) (anti-overselling)
-- 4. Atomic rollback/restock RPC restore_variant_stocks(JSONB)
-- 5. Backend access & Supabase Realtime publication setup
-- Idempotent: Safe to run multiple times in Supabase SQL Editor.
-- ============================================================

-- 1. Product Variants Table
CREATE TABLE IF NOT EXISTS product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  product_type TEXT NOT NULL CHECK (product_type IN ('sneakers', 'apparel', 'products', 'sale_products')),
  size TEXT NOT NULL,
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  low_stock_threshold INTEGER NOT NULL DEFAULT 3 CHECK (low_stock_threshold >= 1),
  sku TEXT UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  UNIQUE (product_type, product_id, size)
);

CREATE INDEX IF NOT EXISTS idx_product_variants_lookup
  ON product_variants(product_type, product_id);

CREATE INDEX IF NOT EXISTS idx_product_variants_stock
  ON product_variants(product_type, product_id, stock);

-- 2. Idempotent Seed for Existing Catalog
-- Core popular sizes (41, 42, 43 for sneakers; M, L for apparel) always start with
-- healthy stock (6-11). Selected edge sizes deterministically demonstrate Low Stock (1-3)
-- and Sold Out (0). ON CONFLICT DO NOTHING ensures live stock is never overwritten.

-- 2a. Seed sneakers
INSERT INTO product_variants (product_id, product_type, size, stock, low_stock_threshold, sku)
SELECT
  s.id AS product_id,
  'sneakers' AS product_type,
  sz.size,
  CASE
    WHEN sz.size IN ('41', '42', '43') THEN 6 + ((s.id + sz.ord) % 6)::INTEGER
    WHEN ((s.id + sz.ord) % 7) = 0 THEN 0
    WHEN ((s.id * 3 + sz.ord) % 5) = 0 THEN 1 + ((s.id + sz.ord) % 3)::INTEGER
    ELSE 4 + ((s.id * 2 + sz.ord) % 9)::INTEGER
  END AS stock,
  3 AS low_stock_threshold,
  'TK-SNK-' || LPAD(s.id::TEXT, 4, '0') || '-' || REPLACE(sz.size, '.', 'H') AS sku
FROM sneakers s
CROSS JOIN unnest(ARRAY['38', '39', '40', '40.5', '41', '42', '42.5', '43', '44', '45', '46'])
  WITH ORDINALITY AS sz(size, ord)
ON CONFLICT (product_type, product_id, size) DO NOTHING;

-- 2b. Seed apparel
INSERT INTO product_variants (product_id, product_type, size, stock, low_stock_threshold, sku)
SELECT
  a.id AS product_id,
  'apparel' AS product_type,
  sz.size,
  CASE
    WHEN sz.size IN ('M', 'L') THEN 6 + ((a.id + sz.ord) % 6)::INTEGER
    WHEN ((a.id + sz.ord) % 6) = 0 THEN 0
    WHEN ((a.id * 2 + sz.ord) % 4) = 0 THEN 1 + ((a.id + sz.ord) % 3)::INTEGER
    ELSE 4 + ((a.id + sz.ord * 2) % 8)::INTEGER
  END AS stock,
  3 AS low_stock_threshold,
  'TK-APR-' || LPAD(a.id::TEXT, 4, '0') || '-' || sz.size AS sku
FROM apparel a
CROSS JOIN unnest(ARRAY['XS', 'S', 'M', 'L', 'XL', 'XXL'])
  WITH ORDINALITY AS sz(size, ord)
ON CONFLICT (product_type, product_id, size) DO NOTHING;

-- 2c. Seed orphan rows from products (rows that do not exist by name in sneakers or apparel)
INSERT INTO product_variants (product_id, product_type, size, stock, low_stock_threshold, sku)
SELECT
  p.id AS product_id,
  'products' AS product_type,
  sz.size,
  CASE
    WHEN sz.size IN ('41', '42', '43', 'M', 'L') THEN 6 + ((p.id + sz.ord) % 6)::INTEGER
    WHEN ((p.id + sz.ord) % 7) = 0 THEN 0
    WHEN ((p.id * 3 + sz.ord) % 5) = 0 THEN 1 + ((p.id + sz.ord) % 3)::INTEGER
    ELSE 4 + ((p.id * 2 + sz.ord) % 9)::INTEGER
  END AS stock,
  3 AS low_stock_threshold,
  'TK-PRD-' || LPAD(p.id::TEXT, 4, '0') || '-' || REPLACE(sz.size, '.', 'H') AS sku
FROM products p
CROSS JOIN LATERAL unnest(
  CASE
    WHEN COALESCE(p.category, '') ~* '(apparel|hoodie|shirt|jacket|pants|jersey)'
      THEN ARRAY['XS', 'S', 'M', 'L', 'XL', 'XXL']
    ELSE ARRAY['38', '39', '40', '40.5', '41', '42', '42.5', '43', '44', '45', '46']
  END
) WITH ORDINALITY AS sz(size, ord)
WHERE NOT EXISTS (
    SELECT 1 FROM sneakers s
    WHERE LOWER(TRIM(s.name)) = LOWER(TRIM(p.name))
  )
  AND NOT EXISTS (
    SELECT 1 FROM apparel a
    WHERE LOWER(TRIM(a.name)) = LOWER(TRIM(p.name))
  )
ON CONFLICT (product_type, product_id, size) DO NOTHING;

-- 2d. Seed orphan rows from sale_products (rows that do not exist by name in sneakers or apparel)
INSERT INTO product_variants (product_id, product_type, size, stock, low_stock_threshold, sku)
SELECT
  sp.id AS product_id,
  'sale_products' AS product_type,
  sz.size,
  CASE
    WHEN sz.size IN ('41', '42', '43', 'M', 'L') THEN 6 + ((sp.id + sz.ord) % 6)::INTEGER
    WHEN ((sp.id + sz.ord) % 7) = 0 THEN 0
    WHEN ((sp.id * 3 + sz.ord) % 5) = 0 THEN 1 + ((sp.id + sz.ord) % 3)::INTEGER
    ELSE 4 + ((sp.id * 2 + sz.ord) % 9)::INTEGER
  END AS stock,
  3 AS low_stock_threshold,
  'TK-SAL-' || LPAD(sp.id::TEXT, 4, '0') || '-' || REPLACE(sz.size, '.', 'H') AS sku
FROM sale_products sp
CROSS JOIN LATERAL unnest(
  CASE
    WHEN COALESCE(sp.category, '') ~* '(apparel|hoodie|shirt|jacket|pants|jersey)'
      THEN ARRAY['XS', 'S', 'M', 'L', 'XL', 'XXL']
    ELSE ARRAY['38', '39', '40', '40.5', '41', '42', '42.5', '43', '44', '45', '46']
  END
) WITH ORDINALITY AS sz(size, ord)
WHERE NOT EXISTS (
    SELECT 1 FROM sneakers s
    WHERE LOWER(TRIM(s.name)) = LOWER(TRIM(sp.name))
  )
  AND NOT EXISTS (
    SELECT 1 FROM apparel a
    WHERE LOWER(TRIM(a.name)) = LOWER(TRIM(sp.name))
  )
ON CONFLICT (product_type, product_id, size) DO NOTHING;

-- 3. Atomic Stock Deduction RPC (Locks rows in deterministic order to prevent deadlocks & overselling)
CREATE OR REPLACE FUNCTION deduct_variant_stocks(p_items JSONB)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
  rec RECORD;
  v_variant_id BIGINT;
  v_current_stock INTEGER;
  v_new_stock INTEGER;
  v_has_any_variant BOOLEAN;
  v_results JSONB := '[]'::JSONB;
BEGIN
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RETURN jsonb_build_object('deducted', FALSE, 'items', '[]'::JSONB);
  END IF;

  FOR rec IN
    SELECT
      TRIM(item->>'product_type') AS product_type,
      (item->>'product_id')::BIGINT AS product_id,
      TRIM(item->>'size') AS size,
      SUM(GREATEST(1, COALESCE((item->>'quantity')::INTEGER, 1)))::INTEGER AS quantity,
      MAX(COALESCE(NULLIF(TRIM(item->>'name'), ''), 'Product')) AS product_name
    FROM jsonb_array_elements(p_items) AS item
    WHERE item ? 'product_type' AND item ? 'product_id' AND item ? 'size'
    GROUP BY 1, 2, 3
    ORDER BY 1, 2, 3
  LOOP
    SELECT id, stock INTO v_variant_id, v_current_stock
    FROM product_variants
    WHERE product_type = rec.product_type
      AND product_id = rec.product_id
      AND size = rec.size
    FOR UPDATE;

    IF NOT FOUND THEN
      SELECT EXISTS(
        SELECT 1
        FROM product_variants
        WHERE product_type = rec.product_type
          AND product_id = rec.product_id
      ) INTO v_has_any_variant;

      IF v_has_any_variant THEN
        RAISE EXCEPTION 'INSUFFICIENT_STOCK|%|%|%|0',
          rec.product_name, rec.size, rec.quantity
          USING ERRCODE = 'P0001';
      END IF;

      -- Product has no seeded variants yet; skip without failing untracked catalog items
      CONTINUE;
    END IF;

    IF v_current_stock < rec.quantity THEN
      RAISE EXCEPTION 'INSUFFICIENT_STOCK|%|%|%|%',
        rec.product_name, rec.size, rec.quantity, v_current_stock
        USING ERRCODE = 'P0001';
    END IF;

    UPDATE product_variants
    SET stock = stock - rec.quantity,
        updated_at = TIMEZONE('utc'::text, NOW())
    WHERE id = v_variant_id
    RETURNING stock INTO v_new_stock;

    v_results := v_results || jsonb_build_array(
      jsonb_build_object(
        'variant_id', v_variant_id,
        'product_type', rec.product_type,
        'product_id', rec.product_id,
        'size', rec.size,
        'deducted', rec.quantity,
        'remaining_stock', v_new_stock
      )
    );
  END LOOP;

  RETURN jsonb_build_object(
    'deducted', jsonb_array_length(v_results) > 0,
    'items', v_results
  );
END;
$$;

-- 4. Atomic Stock Restoration / Rollback RPC
CREATE OR REPLACE FUNCTION restore_variant_stocks(p_items JSONB)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
  rec RECORD;
  v_variant_id BIGINT;
  v_new_stock INTEGER;
  v_results JSONB := '[]'::JSONB;
BEGIN
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RETURN jsonb_build_object('restored', FALSE, 'items', '[]'::JSONB);
  END IF;

  FOR rec IN
    SELECT
      TRIM(item->>'product_type') AS product_type,
      (item->>'product_id')::BIGINT AS product_id,
      TRIM(item->>'size') AS size,
      SUM(GREATEST(1, COALESCE((item->>'quantity')::INTEGER, 1)))::INTEGER AS quantity
    FROM jsonb_array_elements(p_items) AS item
    WHERE item ? 'product_type' AND item ? 'product_id' AND item ? 'size'
    GROUP BY 1, 2, 3
    ORDER BY 1, 2, 3
  LOOP
    SELECT id INTO v_variant_id
    FROM product_variants
    WHERE product_type = rec.product_type
      AND product_id = rec.product_id
      AND size = rec.size
    FOR UPDATE;

    IF FOUND THEN
      UPDATE product_variants
      SET stock = stock + rec.quantity,
          updated_at = TIMEZONE('utc'::text, NOW())
      WHERE id = v_variant_id
      RETURNING stock INTO v_new_stock;

      v_results := v_results || jsonb_build_array(
        jsonb_build_object(
          'variant_id', v_variant_id,
          'product_type', rec.product_type,
          'product_id', rec.product_id,
          'size', rec.size,
          'restored', rec.quantity,
          'remaining_stock', v_new_stock
        )
      );
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'restored', jsonb_array_length(v_results) > 0,
    'items', v_results
  );
END;
$$;

