-- ============================================================
-- TrueKicks Tier 3 Migration:
-- 1. Cloud-Synced Cart (cart_items)
-- 2. Cloud-Synced Wishlist (wishlist_items)
-- 3. Saved Shipping Address Book (user_addresses)
-- 4. Order Tracking, Discounts & Digital Authenticity Columns
-- Idempotent: Safe to run multiple times in Supabase SQL Editor.
-- ============================================================

-- 1. Cloud-Synced Cart Items
CREATE TABLE IF NOT EXISTS cart_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL,
  product_type TEXT NOT NULL DEFAULT 'sneakers',
  name TEXT NOT NULL,
  price NUMERIC NOT NULL,
  image TEXT,
  size TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity >= 1 AND quantity <= 100),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  UNIQUE (user_id, product_id, product_type, size)
);

CREATE INDEX IF NOT EXISTS idx_cart_items_user_id ON cart_items(user_id);

-- 2. Cloud-Synced Wishlist Items
CREATE TABLE IF NOT EXISTS wishlist_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL,
  product_type TEXT NOT NULL DEFAULT 'sneakers',
  name TEXT NOT NULL,
  price NUMERIC NOT NULL,
  discount_price NUMERIC,
  discount_percentage INTEGER DEFAULT 0,
  category TEXT,
  image TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  UNIQUE (user_id, product_id, product_type)
);

CREATE INDEX IF NOT EXISTS idx_wishlist_items_user_id ON wishlist_items(user_id);

-- 3. Saved Shipping Addresses (Address Book)
CREATE TABLE IF NOT EXISTS user_addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT 'Home',
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  city TEXT NOT NULL,
  postal_code TEXT NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE INDEX IF NOT EXISTS idx_user_addresses_user_id ON user_addresses(user_id);

-- 4. Order Tracking, Coupon & Authenticity Extensions on orders
ALTER TABLE orders ADD COLUMN IF NOT EXISTS courier TEXT DEFAULT 'TrueKicks Express';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tracking_number TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipped_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivered_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS authenticity_code TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_code TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount NUMERIC DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_authenticity_code
  ON orders(authenticity_code)
  WHERE authenticity_code IS NOT NULL;

-- 5. Backend Access (TrueKicks uses Express JWT authMiddleware, not Supabase Auth auth.uid())
-- Preferred for production: set SUPABASE_SERVICE_ROLE_KEY in backend/.env & Vercel Backend (bypasses RLS securely on server).
-- If backend uses the anon SUPABASE_KEY instead, disable RLS on these backend-managed tables:
ALTER TABLE cart_items DISABLE ROW LEVEL SECURITY;
ALTER TABLE wishlist_items DISABLE ROW LEVEL SECURITY;
ALTER TABLE user_addresses DISABLE ROW LEVEL SECURITY;
