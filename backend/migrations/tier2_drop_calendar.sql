-- ============================================================
-- TrueKicks Tier 2 Migration:
-- Drop Calendar & Flash Sale Countdown (/drops)
-- 1. drops table (release schedule, limited quota, drop/flash pricing)
-- 2. drop_reminders table (Notify Me per drop + user/email, deduplicated)
-- 3. Idempotent seed linked directly to real sneakers catalog rows
-- 4. RLS & index configuration
-- Idempotent: Safe to run multiple times in Supabase SQL Editor.
-- ============================================================

-- 1. Drops Table
CREATE TABLE IF NOT EXISTS drops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  brand TEXT NOT NULL,
  subtitle TEXT,
  description TEXT,
  drop_type TEXT NOT NULL DEFAULT 'limited_drop'
    CHECK (drop_type IN ('limited_drop', 'flash_sale', 'exclusive_collab')),
  product_id BIGINT,
  product_type TEXT NOT NULL DEFAULT 'sneakers'
    CHECK (product_type IN ('sneakers', 'apparel', 'products', 'sale_products')),
  release_price NUMERIC NOT NULL CHECK (release_price >= 0),
  original_price NUMERIC CHECK (original_price IS NULL OR original_price >= 0),
  image_url TEXT NOT NULL,
  quota_total INTEGER NOT NULL DEFAULT 50 CHECK (quota_total >= 1),
  quota_remaining INTEGER NOT NULL DEFAULT 50 CHECK (quota_remaining >= 0),
  release_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ends_at TIMESTAMP WITH TIME ZONE,
  status TEXT NOT NULL DEFAULT 'upcoming'
    CHECK (status IN ('upcoming', 'live', 'sold_out', 'ended')),
  is_featured BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE INDEX IF NOT EXISTS idx_drops_release_at ON drops(release_at);
CREATE INDEX IF NOT EXISTS idx_drops_status ON drops(status);

-- 2. Drop Reminders (Notify Me) Table
CREATE TABLE IF NOT EXISTS drop_reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drop_id BIGINT NOT NULL REFERENCES drops(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  email TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  UNIQUE (drop_id, email)
);

CREATE INDEX IF NOT EXISTS idx_drop_reminders_drop_id ON drop_reminders(drop_id);
CREATE INDEX IF NOT EXISTS idx_drop_reminders_user_id ON drop_reminders(user_id);
CREATE INDEX IF NOT EXISTS idx_drop_reminders_email ON drop_reminders(email);

-- 3. Idempotent Seed Linked to Real Sneakers Catalog Rows
-- Pulls actual product IDs, prices, and images from `sneakers` so every drop
-- opens real live product details and real-time size stock.
WITH ranked_sneakers AS (
  SELECT
    id,
    name,
    COALESCE(NULLIF(TRIM(category), ''), 'TrueKicks') AS brand,
    COALESCE(price, 1999000)::NUMERIC AS price,
    image_url,
    ROW_NUMBER() OVER (ORDER BY id ASC) AS rn
  FROM sneakers
  WHERE image_url IS NOT NULL AND TRIM(image_url) <> ''
  LIMIT 6
)
INSERT INTO drops (
  slug,
  title,
  brand,
  subtitle,
  description,
  drop_type,
  product_id,
  product_type,
  release_price,
  original_price,
  image_url,
  quota_total,
  quota_remaining,
  release_at,
  ends_at,
  status,
  is_featured
)
SELECT
  CASE rn
    WHEN 1 THEN 'flash-drop-' || id
    WHEN 2 THEN 'limited-release-' || id
    WHEN 3 THEN 'vault-collab-' || id
    WHEN 4 THEN 'midnight-flash-' || id
    WHEN 5 THEN 'archive-edition-' || id
    ELSE 'past-drop-' || id
  END AS slug,
  name AS title,
  brand,
  CASE rn
    WHEN 1 THEN 'Flash Sale · Limited Pairs'
    WHEN 2 THEN 'Hype Queue · Live Now'
    WHEN 3 THEN 'Exclusive Vault Release'
    WHEN 4 THEN 'Weekend Flash Drop'
    WHEN 5 THEN 'Collector Limited Edition'
    ELSE 'Archive Drop · Sold Out'
  END AS subtitle,
  CASE rn
    WHEN 1 THEN 'Alokasi flash sale terbatas dengan verifikasi keaslian digital TrueKicks dan pengiriman ekspres gratis.'
    WHEN 2 THEN 'Rilis terbatas dengan sistem antrean hype untuk memastikan pembagian kuota adil per ukuran.'
    WHEN 3 THEN 'Edisi kurasi terbatas TrueKicks Vault. Aktifkan pengingat agar mendapat akses tepat saat rilis dibuka.'
    WHEN 4 THEN 'Harga spesial flash drop akhir pekan dalam jumlah sangat terbatas untuk anggota TrueKicks.'
    WHEN 5 THEN 'Siluet incaran kolektor dengan stok ketat per ukuran EU dan sertifikat autentikasi digital.'
    ELSE 'Seluruh kuota rilis ini telah habis terjual dalam sesi antrean sebelumnya.'
  END AS description,
  CASE rn
    WHEN 1 THEN 'flash_sale'
    WHEN 2 THEN 'limited_drop'
    WHEN 3 THEN 'exclusive_collab'
    WHEN 4 THEN 'flash_sale'
    WHEN 5 THEN 'limited_drop'
    ELSE 'limited_drop'
  END AS drop_type,
  id AS product_id,
  'sneakers' AS product_type,
  CASE rn
    WHEN 1 THEN ROUND(price * 0.78, -3)
    WHEN 4 THEN ROUND(price * 0.80, -3)
    ELSE price
  END AS release_price,
  CASE rn
    WHEN 1 THEN price
    WHEN 4 THEN price
    ELSE NULL
  END AS original_price,
  image_url,
  CASE rn
    WHEN 1 THEN 40
    WHEN 2 THEN 30
    WHEN 3 THEN 25
    WHEN 4 THEN 60
    WHEN 5 THEN 20
    ELSE 35
  END AS quota_total,
  CASE rn
    WHEN 1 THEN 11
    WHEN 2 THEN 7
    WHEN 3 THEN 25
    WHEN 4 THEN 60
    WHEN 5 THEN 20
    ELSE 0
  END AS quota_remaining,
  CASE rn
    WHEN 1 THEN NOW() - INTERVAL '2 hours'
    WHEN 2 THEN NOW() - INTERVAL '45 minutes'
    WHEN 3 THEN NOW() + INTERVAL '14 hours'
    WHEN 4 THEN NOW() + INTERVAL '2 days 5 hours'
    WHEN 5 THEN NOW() + INTERVAL '5 days 9 hours'
    ELSE NOW() - INTERVAL '3 days'
  END AS release_at,
  CASE rn
    WHEN 1 THEN NOW() + INTERVAL '18 hours'
    WHEN 2 THEN NOW() + INTERVAL '6 hours'
    WHEN 3 THEN NOW() + INTERVAL '38 hours'
    WHEN 4 THEN NOW() + INTERVAL '3 days 5 hours'
    WHEN 5 THEN NOW() + INTERVAL '6 days 9 hours'
    ELSE NOW() - INTERVAL '2 days'
  END AS ends_at,
  CASE rn
    WHEN 1 THEN 'live'
    WHEN 2 THEN 'live'
    WHEN 6 THEN 'sold_out'
    ELSE 'upcoming'
  END AS status,
  (rn = 1) AS is_featured
FROM ranked_sneakers
ON CONFLICT (slug) DO NOTHING;

-- 4. Row Level Security (RLS) Setup
-- `drops` is public catalog data: RLS enabled with public SELECT only.
ALTER TABLE drops ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read drops" ON drops;
CREATE POLICY "Public read drops"
  ON drops
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- `drop_reminders` is managed by Express backend.
-- If your backend uses `SUPABASE_SERVICE_ROLE_KEY`, you may safely change this to:
--   ALTER TABLE drop_reminders ENABLE ROW LEVEL SECURITY;
-- (service_role bypasses RLS automatically while blocking direct browser reads of subscriber emails).
ALTER TABLE drop_reminders DISABLE ROW LEVEL SECURITY;
