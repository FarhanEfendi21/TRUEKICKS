export const resolveTranslation = (language, key, vars = {}) => {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.id;
  const fallbackDict = TRANSLATIONS.id;

  const lookup = (obj, path) =>
    path.split(".").reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);

  let value = lookup(dict, key);
  if (value === undefined) {
    value = lookup(fallbackDict, key);
  }
  if (typeof value !== "string") {
    return value ?? key;
  }

  return value.replace(/\{(\w+)\}/g, (_, token) =>
    vars[token] !== undefined ? String(vars[token]) : `{${token}}`
  );
};

export const translateOrderStatus = (status, language = "id") => {
  const key = String(status || "processing").toLowerCase();
  const translated = resolveTranslation(language, `orderStatus.${key}`);
  return translated === `orderStatus.${key}` ? status || "Processing" : translated;
};
